export const AUTH_TRANSLATION_OVERRIDES = Object.freeze(
  Object.fromEntries(
    Object.keys(AUTH_TRANSLATION_BASE).map((locale) => [
      locale,
      {
        ...AUTH_TRANSLATION_BASE[locale as AdditionalAuthLocale],
        ...AUTH_TRANSLATION_COMPLETIONS[locale as AdditionalAuthLocale],
      },
    ]),
  ) as Record<AdditionalAuthLocale, Record<AuthCopyKey, string>>,
);

export const AUTH_TRANSLATION_COVERAGE = Object.freeze(
  Object.fromEntries(
    Object.entries(AUTH_TRANSLATION_OVERRIDES).map(([locale, values]) => [
      locale,
      {
        translated: Object.keys(values).length,
        total: Object.keys(copy.en).length,
      },
    ]),
  ) as Record<AdditionalAuthLocale, { translated: number; total: number }>,
);

export function authText(locale: AuthLocale, key: AuthCopyKey): string {
  if (locale === "zh-CN" || locale === "en") return copy[locale][key];
  return AUTH_TRANSLATION_OVERRIDES[locale][key] ?? copy.en[key];
}

export type AuthBootstrapErrorKind =
  | "review-isolated"
  | "service-unavailable"
  | "restore-failed"
  | "retry-service-unavailable";

export function authBootstrapErrorText(
  locale: AuthLocale,
  kind: AuthBootstrapErrorKind,
): string {
  if (kind === "review-isolated") return authText(locale, "reviewIsolatedDetail");
  if (kind === "restore-failed") return authText(locale, "restoreFailed");
  if (kind === "retry-service-unavailable") {
    return authText(locale, "retryServiceUnavailable");
  }
  return authText(locale, "serviceUnavailable");
}
